import { build } from 'vite';
import { readFile, writeFile, rm, mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';

const projectRoot = resolve(import.meta.dirname, '../../../..');
const outputDir = resolve(projectRoot, 'build/vivido-editor');
const generatedDir = resolve(projectRoot, 'src/editor/integration/generated');
const configFile = resolve(projectRoot, 'vite.vivido-editor.config.mjs');

await build({ configFile });

let html = await readFile(resolve(outputDir, 'index.html'), 'utf8');
const assetPattern = /<script[^>]+src="([^"]+)"[^>]*><\/script>/;
const assetMatch = html.match(assetPattern);
if (!assetMatch) throw new Error('Vivido custom editor build did not emit a script asset');
const scriptPath = resolve(outputDir, assetMatch[1].replace(/^\//, ''));
const script = await readFile(scriptPath, 'utf8');
if (!script.includes('vividoMedia')) {
  throw new Error('Vivido media bridge name was not included in the custom editor source');
}
html = html.replace(assetMatch[0], () => `<script type="module">${script}</script>`);

await mkdir(generatedDir, { recursive: true });
const generatedPath = resolve(generatedDir, 'VividoMediaEditorSource.ts');
await writeFile(
  generatedPath,
  `// Generated by npm run editor:build:vivido. Do not edit by hand.\nexport const VIVIDO_MEDIA_EDITOR_SOURCE = ${JSON.stringify(html)};\n`,
  'utf8',
);
await rm(outputDir, { recursive: true, force: true });
console.log(`Generated ${generatedPath} (${Buffer.byteLength(html, 'utf8')} bytes)`);
